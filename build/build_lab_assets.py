BLUE=PRGB(0x1F,0x6F,0xEB); INK=PRGB(0x16,0x1B,0x26); GREY=PRGB(0x5B,0x63,0x72)
def _deck(path, slides, title):
    prs=Presentation(); prs.slide_width=PIn(13.333); prs.slide_height=PIn(7.5)
    blank=prs.slide_layouts[6]
    s=prs.slides.add_slide(blank)
    bar=s.shapes.add_shape(1,0,0,prs.slide_width,PIn(0.22)); bar.fill.solid()
    bar.fill.fore_color.rgb=BLUE; bar.line.fill.background(); bar.shadow.inherit=False
    tb=s.shapes.add_textbox(PIn(0.9),PIn(2.6),PIn(11.5),PIn(1.6)); tf=tb.text_frame
    tf.word_wrap=True; r=tf.paragraphs[0].add_run(); r.text=title
    r.font.size=PPt(38); r.font.bold=True; r.font.color.rgb=INK; r.font.name="Arial"
    tb=s.shapes.add_textbox(PIn(0.92),PIn(4.3),PIn(11.5),PIn(0.6))
    r=tb.text_frame.paragraphs[0].add_run(); r.text="Lumina Living Pte Ltd  ·  Sustainable Workspace campaign"
    r.font.size=PPt(15); r.font.color.rgb=GREY; r.font.name="Arial"
    for st,body in slides:
        s=prs.slides.add_slide(blank)
        k=s.shapes.add_shape(1,0,0,PIn(0.24),PIn(1.5)); k.fill.solid()
        k.fill.fore_color.rgb=BLUE; k.line.fill.background(); k.shadow.inherit=False
        tb=s.shapes.add_textbox(PIn(0.85),PIn(0.75),PIn(11.6),PIn(0.9))
        r=tb.text_frame.paragraphs[0].add_run(); r.text=st
        r.font.size=PPt(28); r.font.bold=True; r.font.color.rgb=INK; r.font.name="Arial"
        tb=s.shapes.add_textbox(PIn(0.85),PIn(2.1),PIn(11.6),PIn(4.4)); tf=tb.text_frame
        tf.word_wrap=True
        for i,b in enumerate(body):
            p=tf.paragraphs[0] if i==0 else tf.add_paragraph()
            r=p.add_run(); r.text="•  "+b; r.font.size=PPt(17)
            r.font.color.rgb=INK; r.font.name="Arial"; p.space_after=PPt(10)
    prs.save(path)

