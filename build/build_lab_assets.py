def enquiry_log():
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill, Alignment
    from openpyxl.worksheet.table import Table, TableStyleInfo
    wb=Workbook(); ws=wb.active; ws.title="EnquiryLog"
    hdrs=["Timestamp","Name","Email","Tel","Message"]
    for i,h in enumerate(hdrs,1):
        c=ws.cell(row=1,column=i,value=h)
        c.fill=PatternFill("solid",fgColor="1F6FEB")
        c.font=Font(color="FFFFFF",bold=True,name="Arial",size=10)
    # one seed row so the table has a body; the flow appends beneath it
    ws.append(["2026-09-01T09:00:00Z","Sample Requester","sample@example.com","+65 9000 0000",
               "Seed row - delete after the first successful flow run."])
    t=Table(displayName="EnquiryLog",ref="A1:E2")
    t.tableStyleInfo=TableStyleInfo(name="TableStyleMedium2",showRowStripes=True)
    ws.add_table(t)
    for w,col in zip([26,22,32,18,72],"ABCDE"): ws.column_dimensions[col].width=w
    for c in ws[2]:
        c.font=Font(name="Arial",size=10); c.alignment=Alignment(wrap_text=True,vertical="top")
    ws.freeze_panes="A2"
    wb.save(os.path.join(folder(13),"Enquiry-Log.xlsx"))

