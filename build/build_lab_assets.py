def doc_new(title, kicker):
    d=Document(); d.styles["Normal"].font.name="Arial"; d.styles["Normal"].font.size=Pt(10.5)
    for s in d.sections:
        s.top_margin=Inches(0.85); s.bottom_margin=Inches(0.85)
        s.left_margin=Inches(0.95); s.right_margin=Inches(0.95)
    logo=os.path.join(REPO,"courseware","assets","tertiary-infotech-logo.png")
    if os.path.exists(logo):
        p=d.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.RIGHT
        p.add_run().add_picture(logo,height=Inches(0.38))
    p=d.add_paragraph(); r=p.add_run(kicker); r.font.size=Pt(10); r.font.bold=True
    r.font.color.rgb=RGBColor(0x1F,0x6F,0xEB)
    p=d.add_paragraph(); r=p.add_run(title); r.font.size=Pt(19); r.font.bold=True
    return d
def H(d,t,sz=12):
    p=d.add_paragraph(); r=p.add_run(t); r.font.size=Pt(sz); r.font.bold=True
    p.paragraph_format.space_before=Pt(12); p.paragraph_format.space_after=Pt(3); return p
def P(d,t): d.add_paragraph(t)
def B(d,t): d.add_paragraph(t,style="List Bullet")
def foot(d):
    p=d.add_paragraph(); r=p.add_run(f"{C.TITLE} · {C.COURSE_CODE} · Version {C.VERSION} · © 2026 {C.ORG}")
    r.font.size=Pt(8); r.font.color.rgb=RGBColor(0x8A,0x93,0xA3); p.paragraph_format.space_before=Pt(16)

